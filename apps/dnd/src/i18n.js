export function translate(language, key, parameters = {}) {
  const catalog = TRANSLATIONS[language] ?? TRANSLATIONS.sv;
  const value = catalog[key];
  if (value === undefined) throw new RangeError(`Missing translation: ${language}.${key}`);
  return typeof value === 'function' ? value(parameters) : value;
}

export function localeForLanguage(language) {
  return language === 'en' ? 'en-GB' : 'sv-SE';
}
